#!/usr/bin/env python3
"""Snapshot the paper bot's wallet-quality model (consensus-bot state.json 'wq') into src/wallets.js for the Worker.
Public data only: wallet addresses + display names from public leaderboards, and our computed weights."""
import json, os
B = '/workspace/consensus-bot'
W = json.load(open(os.path.join(B, 'wallets.json')))['wallets']
Q = json.load(open(os.path.join(B, 'state.json'))).get('wq', {}).get('wallets', {})
out = []
for w in W:
    q = Q.get(w['address'], {})
    out.append({'a': w['address'], 'n': w['name'], 'w': q.get('weight', 0.5), 's': 1 if q.get('scalper') else 0,
                'h': q.get('hold'), 'wr': q.get('wr'), 'src': 'kolexplorer' if w['source'].startswith('kolexplorer') else 'kolscan'})
js = ('// Generated by gen_wallets.py from the paper bot wallet-quality model. Do not edit by hand.\n'
      '// a = address, n = public label, w = weight (0 = fast scalper, excluded from the score), s = scalper, h = typical hold (min), wr = win rate %%, src = leaderboard\n'
      'export const WALLETS_AT = %s;\nexport const WALLETS = %s;\n') % (json.dumps(Q and json.load(open(os.path.join(B, 'state.json')))['wq'].get('at')), json.dumps(out, separators=(',', ':')))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'src', 'wallets.js'), 'w').write(js)
print(len(out), 'wallets;', sum(1 for o in out if o['s']), 'scalpers; top', [o['n'] for o in sorted(out, key=lambda o: -o['w'])[:8]])
